#!/usr/bin/env python3
"""Turn Natural Earth's 1:110m land outline into the dot grid behind the
collaboration map, and write it to worldmap.py. Run once; the output is
committed, so the build never needs the network for it."""
import json
import subprocess
from pathlib import Path

HERE = Path(__file__).parent
SRC = "https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-110m.json"

STEP = 2.5                    # degrees between dots
LAT_TOP, LAT_BOT = 75, -56    # crop the poles, which carry no collaborators
SCALE = 4                     # svg units per degree

topo = json.loads(subprocess.run(["curl", "-sL", SRC], capture_output=True,
                                 text=True, check=True).stdout)
(sx, sy), (tx, ty) = topo["transform"]["scale"], topo["transform"]["translate"]

# TopoJSON arcs are delta-encoded and quantised
arcs = []
for arc in topo["arcs"]:
    x = y = 0
    pts = []
    for dx, dy in arc:
        x += dx; y += dy
        pts.append((x * sx + tx, y * sy + ty))
    arcs.append(pts)


def ring(idx):
    pts = []
    for i in idx:
        a = arcs[i] if i >= 0 else arcs[~i][::-1]
        pts.extend(a if not pts else a[1:])
    return pts


polys = []
for geom in topo["objects"]["land"]["geometries"]:
    shapes = geom["arcs"] if geom["type"] == "MultiPolygon" else [geom["arcs"]]
    for shape in shapes:
        polys.append([ring(r) for r in shape])


def inside(lon, lat, pts):
    hit = False
    j = len(pts) - 1
    for i in range(len(pts)):
        xi, yi = pts[i]; xj, yj = pts[j]
        if (yi > lat) != (yj > lat) and lon < (xj - xi) * (lat - yi) / (yj - yi) + xi:
            hit = not hit
        j = i
    return hit


def land(lon, lat):
    # the first ring is the outline, the rest are holes (lakes)
    return any(inside(lon, lat, p[0]) and not any(inside(lon, lat, h) for h in p[1:])
               for p in polys)


dots = []
lat = LAT_TOP
while lat >= LAT_BOT:
    lon = -180 + STEP / 2
    while lon < 180:
        if land(lon, lat):
            dots.append((round((lon + 180) * SCALE), round((LAT_TOP - lat) * SCALE)))
        lon += STEP
    lat -= STEP

path = "".join(f"M{x} {y}h0" for x, y in dots)
(HERE / "worldmap.py").write_text(
    "# Generated by make_worldmap.py from Natural Earth 1:110m land (public domain).\n"
    f"# Equirectangular, {STEP}° grid, latitudes {LAT_TOP} to {LAT_BOT}, {SCALE} units per degree.\n"
    f"STEP, LAT_TOP, LAT_BOT, SCALE = {STEP}, {LAT_TOP}, {LAT_BOT}, {SCALE}\n"
    f"WIDTH, HEIGHT = {360 * SCALE}, {(LAT_TOP - LAT_BOT) * SCALE}\n"
    f'DOTS = "{path}"\n', encoding="utf-8")
print(f"{len(dots)} land dots, {len(path):,} bytes of path")
