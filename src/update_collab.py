#!/usr/bin/env python3
"""Build the collaboration map's data from OpenAlex: every institution that
appears on a co-author's affiliation in the papers listed in pubs.py,
grouped by city, with how many of those papers it shares. Writes collab.py,
then rebuilds both pages.

OpenAlex is open and free, so this works from anywhere (including a
scheduled GitHub Action). Affiliations are as printed on each paper.
"""
import difflib
import json
import re
import subprocess
import sys
import urllib.parse
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
from pubs import PUBS  # noqa: E402

ORCID = "0000-0002-3339-6668"
HOME_ID = "I79619799"    # University of Birmingham — the hub, not a collaborator
API = "https://api.openalex.org"


def get(path, **params):
    params["mailto"] = "site@arvanitidismichail.com"
    url = f"{API}/{path}?{urllib.parse.urlencode(params)}"
    return json.loads(subprocess.run(["curl", "-sL", url], capture_output=True,
                                     text=True, check=True).stdout)


def norm(t):
    return re.sub(r"[^a-z0-9]+", " ", (t or "").lower()).strip()


ours = {norm(p["title"]) for p in PUBS if p["status"] in ("published", "review")}
works = get("works", filter=f"author.orcid:{ORCID}", **{"per-page": 200},
            select="title,authorships")["results"]

# institution -> titles it shares with us (a set, so a preprint and its
# published version count once)
shared = defaultdict(set)
names = {}
for w in works:
    t = norm(w["title"])
    # titles differ in small ways between databases ("the", "rate", quotes)
    if not any(difflib.SequenceMatcher(None, t, o).ratio() >= 0.9 for o in ours):
        continue
    for a in w["authorships"]:
        for inst in a["institutions"]:
            iid = inst["id"].rsplit("/", 1)[-1]
            if iid != HOME_ID:
                shared[iid].add(t)
                names[iid] = inst["display_name"]

geo = {}
ids = list(shared)
for k in range(0, len(ids), 50):
    for inst in get("institutions", filter="openalex:" + "|".join(ids[k:k + 50]),
                    select="id,geo", **{"per-page": 50})["results"]:
        geo[inst["id"].rsplit("/", 1)[-1]] = inst["geo"]

cities = {}
for iid, titles in shared.items():
    g = geo.get(iid)
    if not g or g.get("latitude") is None:
        continue
    key = (g["city"], g["country_code"])
    c = cities.setdefault(key, dict(city=g["city"], country=g["country"],
                                    lat=round(g["latitude"], 2), lon=round(g["longitude"], 2),
                                    titles=set(), institutions=[]))
    c["titles"] |= titles
    c["institutions"].append(names[iid])

rows = sorted(cities.values(), key=lambda c: (-len(c["titles"]), c["city"]))
lines = [
    "# Generated by update_collab.py from OpenAlex — co-authors' affiliations on the",
    "# papers in pubs.py, grouped by city. Refresh with:  python3 update_collab.py",
    "HOME = dict(city=\"Birmingham\", lat=52.45, lon=-1.93)",
    "",
    "CITIES = [",
]
for c in rows:
    lines.append(f"    dict(city={c['city']!r}, country={c['country']!r}, lat={c['lat']}, lon={c['lon']}, "
                 f"papers={len(c['titles'])}, institutions={sorted(set(c['institutions']))!r}),")
lines += ["]", ""]
(HERE / "collab.py").write_text("\n".join(lines), encoding="utf-8")
print(f"{len(rows)} cities, {len({i for c in rows for i in c['institutions']})} institutions, "
      f"{len(set().union(*[c['titles'] for c in rows]))} papers with outside co-authors")

if "--no-build" not in sys.argv:
    subprocess.run([sys.executable, str(HERE / "build.py")], check=True)
